// TestRunRecordsFingerprintOnlyAfterGenerating: the fingerprint is the record of
// a *completed* analysis, so it is written after the generators succeed.
// shouldSkipAnalysis used to write it before they ran, which meant a failed run
// left a valid fingerprint behind: the next run took the skip path, printed
// "Analysis unchanged since last run" and listed project.json as "(cached)" while
// the file did not exist — a check reporting success for work it had not done.
func TestRunRecordsFingerprintOnlyAfterGenerating(t *testing.T) {
	project := newFixture(t, map[string]string{
		"go.mod":                         "module x\n",
		"main.go":                        "package main\n",
		".plaesy/analysis/project.json/": "", // blocks the first generation
	})
	if err := Run(Options{ProjectPath: project, NoGraph: true}); err == nil {
		t.Fatal("expected the first run to fail while writing project.json")
	}

	// Unblock the writer. The failed run left no fingerprint behind, so this run
	// must regenerate rather than claim the analysis is cached.
	if err := os.RemoveAll(filepath.Join(project, filepath.FromSlash(analysisDirName), "project.json")); err != nil {
		t.Fatalf("remove blocker: %v", err)
	}
	logs := captureLogs(t)
	if err := Run(Options{ProjectPath: project, NoGraph: true}); err != nil {
		t.Fatalf("second Run: %v", err)
	}
	if _, err := os.Stat(filepath.Join(project, filepath.FromSlash(analysisDirName), "project.json")); err != nil {
		t.Fatalf("the second run must regenerate project.json: %v", err)
	}
	if out := logs.joined(); strings.Contains(out, "Skipping regeneration") {
		t.Errorf("a failed run must not leave a fingerprint that skips the next one:\n%s", out)
	}
}

