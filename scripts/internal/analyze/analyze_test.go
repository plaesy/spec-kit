func TestDefaultLogFunctionsWritePrefixedLines(t *testing.T) {
	r, w, err := os.Pipe()
	if err != nil {
		t.Fatalf("pipe: %v", err)
	}
	origStdout := os.Stdout
	os.Stdout = w
	func() {
		defer func() {
			os.Stdout = origStdout
			_ = w.Close()
		}()
		Logf("hello %s", "world")
		Successf("done %d", 7)
	}()
	data, err := io.ReadAll(r)
	if err != nil {
		t.Fatalf("read captured stdout: %v", err)
	}
	got := string(data)
	mustContain(t, got, "[INFO] hello world\n")
	mustContain(t, got, "[SUCCESS] done 7\n")
}
