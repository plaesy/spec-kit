func TestRunSurvivesGraphFailure(t *testing.T) {
	logs := captureLogs(t)
	// An empty project has no source files, so graph.Build fails; the summary
	// artifacts must still be produced and the error must be logged, not fatal.
	project := newFixture(t, map[string]string{"notes.untracked": "x"})
	if err := Run(Options{ProjectPath: project}); err != nil {
		t.Fatalf("Run must not fail when the graph build fails: %v", err)
	}
	analysisDir := filepath.Join(project, filepath.FromSlash(analysisDirName))
	if _, err := os.Stat(filepath.Join(analysisDir, "project.json")); err != nil {
		t.Errorf("project.json should still be generated: %v", err)
	}
	out := logs.joined()
	mustContain(t, out, "Graph build skipped/failed; summary files remain valid.")

	// A run whose graph build failed must not leave a fingerprint behind. The
	// fingerprint is the claim that every listed artifact exists, and the fast
	// path above trusts it: with one recorded, the *next* run took the skip
	// path, printed the three missing graph files as "(cached)", and never
	// built the graph again without --force. The failure was announced once
	// and then cached away.
	if _, err := os.Stat(filepath.Join(analysisDir, ".analysis-fingerprint")); !os.IsNotExist(err) {
		t.Errorf("a failed graph build must not record the analysis fingerprint (stat err=%v)", err)
	}
	// Same reason: "Generated files" is a list of what is on disk, not of
	// what the flags asked for.
	mustNotContain(t, out, "project.graph.json - Dependency graph")
	mustNotContain(t, out, "project.html - Interactive graph visualization")
	mustNotContain(t, out, "reports.md - Graph report")
	mustContain(t, out, "Not recording the analysis fingerprint")

	// And the recovery path works: a second run on the same project must
	// regenerate rather than report the missing graph as cached.
	logs2 := captureLogs(t)
	if err := Run(Options{ProjectPath: project}); err != nil {
		t.Fatalf("second Run: %v", err)
	}
	mustNotContain(t, logs2.joined(), "Analysis unchanged since last run")
}

