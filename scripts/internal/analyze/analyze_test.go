func TestFileNames(t *testing.T) {
	cases := []struct {
		name  string
		files []fileInfo
		want  []string
	}{
		{"empty", nil, []string{}},
		{"single", files("main.go"), []string{"main.go"}},
		{"nested", files("a/b/c.go", "a/d.go"), []string{"a/b/c.go", "a/d.go"}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := fileNames(tc.files); !equalStrings(got, tc.want) {
				t.Errorf("fileNames() = %v, want %v", got, tc.want)
			}
		})
	}
}

func equalStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func TestTrimVersion(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string
	}{
		{"empty", "", ""},
		{"clean", "1.2.3", "1.2.3"},
		{"trailing newline", "1.2.3\n", "1.2.3"},
		{"trailing crlf", "1.2.3\r\n", "1.2.3"},
		{"trailing space", "1.2.3 ", "1.2.3"},
		{"mixed trailing whitespace", "1.2.3\n\n  \r", "1.2.3"},
		{"leading whitespace is preserved", " 1.2.3\n", " 1.2.3"},
		{"inner whitespace is preserved", "1.2.3 v2\n", "1.2.3 v2"},
		{"whitespace only", "\n\r ", ""},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := trimVersion(tc.in); got != tc.want {
				t.Errorf("trimVersion(%q) = %q, want %q", tc.in, got, tc.want)
			}
		})
	}
}

func TestFrameworkVersionFor(t *testing.T) {
	orig := common.Version
	t.Cleanup(func() { common.Version = orig })

	t.Run("ldflags version wins", func(t *testing.T) {
		common.Version = "3.4.5"
		if got := frameworkVersionFor(t.TempDir()); got != "3.4.5" {
			t.Errorf("frameworkVersionFor() = %q, want 3.4.5", got)
		}
	})

	// With no injected version the analyzer falls back to a VERSION file two
	// directories above the running executable, then to the "0.0.1" default.
	for _, injected := range []string{"", "0.0.0"} {
		t.Run("fallback for version "+quote(injected), func(t *testing.T) {
			common.Version = injected
			want := "0.0.1"
			if exe, err := os.Executable(); err == nil {
				candidate := filepath.Join(filepath.Dir(exe), "..", "..", "VERSION")
				if data, err := os.ReadFile(candidate); err == nil {
					want = trimVersion(string(data))
				}
			}
			got := frameworkVersionFor(t.TempDir())
			if got != want {
				t.Errorf("frameworkVersionFor() = %q, want %q", got, want)
			}
			if got == "" {
				t.Error("frameworkVersionFor must never return an empty version")
			}
		})
	}
}

