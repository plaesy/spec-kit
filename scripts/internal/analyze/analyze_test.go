func TestBuildGraph(t *testing.T) {
	project := newFixture(t, map[string]string{
		"README.md":        "# doc\n\nSee [main](main.go).\n",
		"main.go":          "package main\n",
		"internal/util.go": "package internal\n",
	})
	analysisDir := filepath.Join(project, filepath.FromSlash(analysisDirName))

	if err := buildGraph(project, false); err != nil {
		t.Fatalf("buildGraph: %v", err)
	}
	graphPath := filepath.Join(analysisDir, "project.graph.json")
	for _, name := range []string{"project.graph.json", "project.html", "reports.md", ".fingerprint"} {
		if _, err := os.Stat(filepath.Join(analysisDir, name)); err != nil {
			t.Errorf("expected %s: %v", name, err)
		}
	}
	fp := readFileString(t, filepath.Join(analysisDir, ".fingerprint"))
	if strings.TrimSpace(fp) == "" {
		t.Error("expected a non-empty graph fingerprint")
	}

	// Second incremental build: unchanged sources, so the artifacts are left
	// untouched.
	const sentinel = "UNTOUCHED"
	if err := os.WriteFile(graphPath, []byte(sentinel), 0o644); err != nil {
		t.Fatalf("seed sentinel: %v", err)
	}
	if err := buildGraph(project, false); err != nil {
		t.Fatalf("second buildGraph: %v", err)
	}
	if got := readFileString(t, graphPath); got != sentinel {
		t.Error("incremental build should have skipped because the source fingerprint is unchanged")
	}

	// Forced build always regenerates.
	if err := buildGraph(project, true); err != nil {
		t.Fatalf("forced buildGraph: %v", err)
	}
	if got := readFileString(t, graphPath); got == sentinel {
		t.Error("forced build should have regenerated project.graph.json")
	}

	// A source change invalidates the incremental fingerprint.
	if err := os.WriteFile(filepath.Join(project, "added.go"), []byte("package main\n"), 0o644); err != nil {
		t.Fatalf("write added.go: %v", err)
	}
	if err := os.WriteFile(graphPath, []byte(sentinel), 0o644); err != nil {
		t.Fatalf("seed sentinel: %v", err)
	}
	if err := buildGraph(project, false); err != nil {
		t.Fatalf("third buildGraph: %v", err)
	}
	if got := readFileString(t, graphPath); got == sentinel {
		t.Error("a new source file must invalidate the incremental graph build")
	}
}

